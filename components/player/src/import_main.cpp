#include "ff/playback.hpp"
#include <filesystem>
#include <fstream>
#include <iostream>
#include <sys/stat.h>

// The orchestration tool creates a private staging directory and atomically
// publishes it only after this validator/transaction succeeds. This executable
// never opens a browser profile and refuses an existing SQLite destination.
int main(int argc,char** argv){
  umask(0077);
  if(argc!=3){std::cerr<<"Usage: ff-player-import NORMALIZED.json EMPTY_DIRECTORY\n";return 2;}
  try{
    std::ifstream input(argv[1],std::ios::binary);ff::require(bool(input),"migration_read","Cannot read normalized migration document");
    std::string body(ff::max_frame+1,'\0');input.read(body.data(),body.size());body.resize(input.gcount());
    auto document=ff::parse(body);
    ff::fields(document,{"format","version","state","provenance"});
    ff::require(document.value("format","")=="ff-player-native-import"&&document.value("version",0)==1,"migration_version","Unsupported migration format");
    ff::require(document.contains("state")&&document["state"].is_object(),"migration_invalid","Missing native state");
    auto directory=std::filesystem::path(argv[2]);
    ff::require(std::filesystem::is_directory(directory)&&std::filesystem::is_empty(directory),"migration_exists","Import destination must be an empty staging directory");
    // No persisted success, occurrence, overlay, renderer or input state is
    // accepted. These identities must be generated by the next live host.
    const auto& state=document["state"];
    ff::fields(state,{"version","playlist","index","context","stopped","sleeping","paused","loop","shuffle","order","settings","policy","history","historyIncomplete","boot","schedule","playlistUrl"});
    {
      ff::Store store((directory/"state.sqlite").string());store.save(state);
      ff::Playback validate(store);
      ff::require(!validate.visible(),"migration_invalid","Import manufactured presentation");
    }
    std::ofstream provenance(directory/"migration.json",std::ios::binary);
    ff::require(bool(provenance),"migration_write","Cannot write import provenance");
    provenance<<document.value("provenance",ff::Json::object()).dump(2)<<'\n';provenance.close();
    ff::require(bool(provenance),"migration_write","Cannot finish import provenance");
    std::cout<<"Validated native state in staging directory; no rendering success imported\n";
  }catch(const std::exception& error){std::cerr<<"ff-player-import: "<<error.what()<<'\n';return 1;}
}
